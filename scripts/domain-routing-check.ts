import assert from "node:assert/strict";
import { domainRedirect, isPortalPath, portalCallbackPath } from "../src/lib/domains";
const origins = { site: "https://unilagtaekwondo.org", portal: "https://portal.unilagtaekwondo.org" };
const route = (url: string) => domainRedirect(new URL(url), origins)?.toString() ?? null;
assert.equal(route("https://unilagtaekwondo.org/"), null);
assert.equal(route("https://unilagtaekwondo.org/register"), "https://portal.unilagtaekwondo.org/register");
assert.equal(route("https://unilagtaekwondo.org/setup-account?token=example-token"), "https://portal.unilagtaekwondo.org/setup-account?token=example-token");
assert.equal(route("https://unilagtaekwondo.org/dashboard/coach?tab=attendance"), "https://portal.unilagtaekwondo.org/dashboard/coach?tab=attendance");
assert.equal(route("https://unilagtaekwondo.org/api/auth/session"), "https://portal.unilagtaekwondo.org/api/auth/session");
assert.equal(route("https://unilagtaekwondo.org/examiner/example-token"), "https://portal.unilagtaekwondo.org/examiner/example-token");
assert.equal(route("https://portal.unilagtaekwondo.org/"), "https://portal.unilagtaekwondo.org/dashboard");
assert.equal(route("https://portal.unilagtaekwondo.org/privacy?source=portal"), "https://unilagtaekwondo.org/privacy?source=portal");
assert.equal(route("https://portal.unilagtaekwondo.org/login"), null);
assert.equal(route("https://portal.unilagtaekwondo.org/dashboard/coach"), null);
assert.equal(route("https://portal.unilagtaekwondo.org/brand/club-logo.png"), null);
assert.equal(route("https://portal.unilagtaekwondo.org/_next/static/chunk.js"), null);
assert.equal(route("http://localhost:5213/login"), null);
assert.equal(route("https://preview.example/login"), null);
assert.equal(domainRedirect(new URL("https://unilagtaekwondo.org/login"), {site:"",portal:""}), null);
assert.equal(new URL(route("https://portal.unilagtaekwondo.org//evil.example/path")!).origin, origins.site);
assert.equal(isPortalPath("/dashboard-other"), false);
assert.equal(isPortalPath("/login/"), true);
assert.equal(portalCallbackPath("/dashboard/checkin/test?source=qr", origins.portal), "/dashboard/checkin/test?source=qr");
assert.equal(portalCallbackPath("https://evil.example/dashboard", origins.portal), "/dashboard");
assert.equal(portalCallbackPath("//evil.example/dashboard", origins.portal), "/dashboard");
assert.equal(portalCallbackPath("/\\evil.example/dashboard", origins.portal), "/dashboard");
assert.equal(portalCallbackPath("/login", origins.portal), "/dashboard");
console.log("Portal/public routing, local development, query preservation, assets, and callback safety checks passed.");
